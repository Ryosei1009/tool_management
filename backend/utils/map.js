// ピン座標（%）から棚番号（A1〜A9）を返す。
const getMapName = (x, y) => {
    if (x === null || x === undefined || y === null || y === undefined) return null;
    if (x >= 0 && x < 38.94354952265509 && y >= 0 && y < 35.44580756532781) return 'A1';
    if (x >= 0 && x < 38.94354952265509 && y >= 35.44580756532781 && y < 59.757463803209234) return 'A2';
    if (x >= 0 && x < 32.5172614380738 && y >= 59.757463803209234 && y <= 100) return 'A3';
    if (x >= 38.94354952265509 && x < 54.854700422367785 && y >= 0 && y < 35.44580756532781) return 'A4';
    if (x >= 38.94354952265509 && x < 58.415741419863934 && y >= 35.44580756532781 && y < 59.757463803209234) return 'A5';
    if (x >= 32.5172614380738 && x < 58.415741419863934 && y >= 59.757463803209234 && y <= 100) return 'A6';
    if (x >= 54.854700422367785 && x <= 100 && y >= 0 && y < 35.44580756532781) return 'A7';
    if (x >= 58.415741419863934 && x <= 100 && y >= 35.44580756532781 && y < 61.90216119216665) return 'A8';
    if (x >= 58.415741419863934 && x <= 100 && y >= 61.90216119216665 && y <= 100) return 'A9';
    return null;
};

module.exports = { getMapName };
